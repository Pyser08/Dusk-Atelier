const GENERIC = ["이 항목에서 설정이 어긋나 보여서 알려드려요. 저장은 막지 않아요.", "표시된 항목으로 이동해 내용을 확인하세요. 의도한 설정이면 무시해도 돼요."];

export function explainIssue(issue) {
  const msg = String(issue?.msg ?? "");
  for (const [re, why, fix] of RULES) if (re.test(msg)) return { why, fix };
  const [why, fix] = GENERIC;
  return { why, fix };
}
// 무시 표시용 고정 열쇠: 같은 경고는 같은 열쇠
export const issueKey = (i) => `${i.level}|${i.tab ?? ""}|${i.msg}`;
// {active, ignored}로 나눈다. 오류(err)는 무시할 수 없다.
export function splitIssues(list, ignored) {
  const set = new Set(ignored ?? []), active = [], skipped = [];
  for (const i of list) (i.level !== "err" && set.has(issueKey(i)) ? skipped : active).push(i);
  return { active, ignored: skipped };
}
