// 2.2.0 글래스 테마 6종 + 밝은·어두운 판: 꾸미기에서 고르기·저장, 밝기 바꾸면 판이 바뀜, 색을 직접 고르면 '내 강조색', 글래스 끄기·고대비
import { createRequire } from "node:module";
import { build } from "/opt/npm-tools/node_modules/esbuild/lib/main.js";
const { chromium } = createRequire("/opt/npm-tools/node_modules/")("playwright");
const r = await build({ entryPoints: ["tests/e2e/app.entry.js"], bundle: true, write: false, format: "iife", platform: "browser", logLevel: "error", define: { __VERSION__: '"test"', __CHANGELOG__: '""' }, alias: { fflate: process.cwd() + "/src/vendor/fflate.js" }, loader: { ".json": "json" } });
const out = [], ok = (n, c, x = "") => { out.push(c); console.log((c ? "✔ " : "✘ ") + n + (c ? "" : "  → " + x)); };
const browser = await chromium.launch();
const errs = [];
for (const [tag, vp] of [["PC", { width: 1280, height: 860 }], ["모바일", { width: 390, height: 844 }]]) {
  const page = await (await browser.newContext({ viewport: vp, ...tag === "모바일" ? { hasTouch: true, isMobile: true } : {} })).newPage(); page.setDefaultTimeout(5000);
  page.on("pageerror", (e) => errs.push(e.message));
  await page.setContent("<!doctype html><meta name=viewport content=\"width=device-width,initial-scale=1\"><body style='margin:0'></body>"); await page.addScriptTag({ content: r.outputFiles[0].text });
  await page.evaluate(() => window.bootApp({ "rbm:seenVersion:v1": "9.9.9", "rbm:ui:v1": JSON.stringify({ tourDone: true, tourVer: 99, simpleNoticeDone: true, theme: { mode: "dark" } }) }));
  await page.waitForTimeout(400);
  const ui = () => page.evaluate(() => JSON.parse(__api.store["rbm:ui:v1"] ?? "{}").theme ?? {});
  const win = () => page.evaluate(() => { const w = document.querySelector(".rb-win"), c = getComputedStyle(w); return { glass: w.classList.contains("rb-skin-glass"), light: w.classList.contains("rb-glass-light"), g: w.dataset.gtheme, bg: c.backgroundColor, img: c.backgroundImage, acc: getComputedStyle(document.querySelector(".rb-root")).getPropertyValue("--rb-acc-a").trim() }; });
  let w = await win();
  ok(`[${tag}] 기본: 글래스·Dusk 황혼·어두운 판`, w.glass && !w.light && w.g === "dusk" && /radial-gradient/.test(w.img), JSON.stringify(w));
  await page.evaluate(() => window.__app.ctx.go("look")); await page.waitForTimeout(400);
  const look = ".rb-mem2[data-page=look]";
  ok(`[${tag}] 꾸미기: 글래스 테마 23개(22종 + 내 강조색), 기본 Dusk 황혼 눌림`, (await page.locator(`${look} .rb-gpick`).count()) === 23 && (await page.locator(`${look} .rb-gpick[aria-pressed=true]`).getAttribute("data-id")) === "dusk");
  await page.locator(`${look} .rb-gpick[data-id=aurora]`).click(); await page.waitForTimeout(400);
  w = await win();
  ok(`[${tag}] 오로라 고르면 바로 적용·저장`, w.g === "aurora" && (await ui()).gtheme === "aurora" && w.bg === "rgb(7, 26, 31)", JSON.stringify(w));
  await page.locator(`${look} .rb-seg[aria-label=밝기] button`, { hasText: "밝게" }).click(); await page.waitForTimeout(400);
  w = await win();
  ok(`[${tag}] 밝게 → 밝은 판(오로라 밝은 바탕)`, w.glass && w.light && w.bg === "rgb(239, 251, 247)", JSON.stringify(w));
  const txt = await page.evaluate(() => getComputedStyle(document.querySelector(".rb-win")).getPropertyValue("--rb-text").trim());
  ok(`[${tag}] 밝은 판 글자는 어두운 색`, txt === "#1f1a33", txt);
  await page.locator(`${look} .rb-accpick`).first().click(); await page.waitForTimeout(400);
  ok(`[${tag}] 강조 색을 직접 고르면 '내 강조색'으로`, (await ui()).gtheme === "mine" && (await page.locator(`${look} .rb-gpick[aria-pressed=true]`).getAttribute("data-id")) === "mine");
  await page.locator(`${look} .rb-seg[aria-label=밝기] button`, { hasText: "어둡게" }).click(); await page.locator(`${look} .rb-gpick[data-id=galaxy]`).click(); await page.waitForTimeout(300);
  ok(`[${tag}] 새 테마(은하) 적용`, (await win()).g === "galaxy" && (await win()).bg === "rgb(11, 8, 32)");
  ok(`[${tag}] 미리보기도 고른 글래스 테마 강조색`, await page.evaluate(() => getComputedStyle(document.querySelector(".rb-look-side .is-scoped, .is-scoped")).getPropertyValue("--rb-acc-a").trim().toLowerCase() === "#9b7bff"));
  await page.locator(`${look} .rb-gpick[data-id=mono]`).click(); await page.waitForTimeout(400);
  w = await win();
  ok(`[${tag}] 모노 · 어둡게`, w.g === "mono" && !w.light && w.bg === "rgb(20, 20, 24)", JSON.stringify(w));
  await page.locator(`${look} #rb-look-shape summary`).click();
  const glassRow = page.locator(`${look} .rb-toggle`, { hasText: "글래스 화면" });
  await glassRow.locator("[role=switch]").click(); await page.waitForTimeout(400);
  w = await win();
  ok(`[${tag}] 글래스 화면 끄면 예전 모양`, !w.glass && (await ui()).skin === "classic", JSON.stringify(w));
  await glassRow.locator("[role=switch]").click(); await page.waitForTimeout(400);
  ok(`[${tag}] 다시 켬`, (await win()).glass);
  await page.close();
}
ok("오류 없음", !errs.length, errs.join(";"));
await browser.close();
process.exit(out.every(Boolean) ? 0 : 1);
