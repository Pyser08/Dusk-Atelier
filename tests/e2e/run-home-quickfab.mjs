// 홈 빠른 설정: 떠 있는 버튼 없애기 토글 저장, 길면 스크롤·아래 흐림 표시 (11-22)
import { createRequire } from "node:module";
import { build } from "/opt/npm-tools/node_modules/esbuild/lib/main.js";
const { chromium } = createRequire("/opt/npm-tools/node_modules/")("playwright");
const r = await build({ entryPoints: ["tests/e2e/app.entry.js"], bundle: true, write: false, format: "iife", platform: "browser", logLevel: "error", define: { __VERSION__: '"test"', __CHANGELOG__: '""' }, alias: { fflate: process.cwd() + "/src/vendor/fflate.js" }, loader: { ".json": "json" } });
const out = [], ok = (n, c, x = "") => { out.push(c); console.log((c ? "✔ " : "✘ ") + n + (c ? "" : "  → " + x)); };
const browser = await chromium.launch();
const page = await (await browser.newContext({ viewport: { width: 1280, height: 800 } })).newPage(); page.setDefaultTimeout(5000);
const errs = []; page.on("pageerror", (e) => errs.push(e.message));
await page.setContent("<!doctype html><body style='margin:0'></body>"); await page.addScriptTag({ content: r.outputFiles[0].text });
await page.evaluate(() => window.bootApp({ "rbm:seenVersion:v1": "9.9.9", "rbm:ui:v1": JSON.stringify({ promptIntroDone: true, tourDone: true, tourVer: 99 }) }, { host: true }));
await page.waitForTimeout(300);
const sw = page.locator(".rb-story-helper [role=switch][aria-label='떠 있는 버튼 없애기']");
ok("토글이 있고 처음엔 꺼짐", (await sw.getAttribute("aria-checked")) === "false");
await sw.click(); await page.waitForTimeout(200);
ok("켜면 버튼 설정이 off로 저장", (await page.evaluate(() => __api.store["dusk.ui.memoryButton"])) === "off");
await sw.click(); await page.waitForTimeout(200);
ok("끄면 on으로 저장", (await page.evaluate(() => __api.store["dusk.ui.memoryButton"])) === "on");
const card = page.locator(".rb-qs-scroll");
await card.evaluate((el) => { el.style.maxHeight = "120px"; el.dispatchEvent(new Event("scroll")); });
await page.waitForTimeout(150);
ok("넘치면 아래 흐림 표시", ...await card.evaluate((el) => { const cs = getComputedStyle(el), m = cs.maskImage || cs.webkitMaskImage; return [el.classList.contains("rb-qs-more") && el.scrollHeight > el.clientHeight && /linear-gradient/.test(m), JSON.stringify([el.className, el.scrollHeight, el.clientHeight, m])]; }));
await card.evaluate((el) => { el.scrollTop = el.scrollHeight; el.dispatchEvent(new Event("scroll")); });
await page.waitForTimeout(150);
ok("끝까지 내리면 흐림 사라짐", await card.evaluate((el) => !el.classList.contains("rb-qs-more")));
await card.evaluate((el) => { el.scrollTop = 0; el.dispatchEvent(new Event("scroll")); }); await page.waitForTimeout(250);
await card.screenshot({ path: process.env.SHOT || "/tmp/qs.png" });
ok("페이지 오류 없음", !errs.length, errs.join(" | "));
await browser.close();
process.exit(out.every(Boolean) ? 0 : 1);
