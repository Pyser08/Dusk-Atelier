// 인물 위키 → 더보기 → '봇 로어북으로 내보내기': 고른 인물만, 정리된 정보만, 표식으로 갱신. 클라우드 샌드박스: /opt/npm-tools
import { createRequire } from "node:module";
import { build } from "/opt/npm-tools/node_modules/esbuild/lib/main.js";
const { chromium } = createRequire("/opt/npm-tools/node_modules/")("playwright");
const r = await build({ entryPoints: ["tests/e2e/app.entry.js"], bundle: true, write: false, format: "iife", platform: "browser", logLevel: "error", define: { __VERSION__: '"test"', __CHANGELOG__: '""' }, alias: { fflate: process.cwd() + "/src/vendor/fflate.js" }, loader: { ".json": "json" } });
const out = [], ok = (n, c, x = "") => { out.push(c); console.log((c ? "✔ " : "✘ ") + n + (c ? "" : "  → " + x)); };
const browser = await chromium.launch();
const page = await (await browser.newContext({ viewport: { width: 1280, height: 860 } })).newPage(); page.setDefaultTimeout(5000);
const errs = []; page.on("pageerror", (e) => errs.push(e.message));
await page.setContent("<!doctype html><body style='margin:0'></body>"); await page.addScriptTag({ content: r.outputFiles[0].text });
await page.evaluate(() => window.bootApp({ "rbm:seenVersion:v1": "1.7.0-dev", "rbm:memoryEmbeddingGuide:shown:v1": "1", "rbm:ui:v1": JSON.stringify({ promptIntroDone: true, tourDone: true, tourVer: 99, onboardDone: true }) }, { memory: true, story: true }));
await page.waitForTimeout(300);
const clickText = (sel, re) => page.evaluate(([sel, re]) => { const el = [...document.querySelectorAll(sel)].find((e) => new RegExp(re).test(e.textContent.trim())); el?.click(); return !!el; }, [sel, re]);
await page.evaluate(() => __app.ctx.go("memory")); await page.waitForTimeout(800);
await clickText(".rb-mem2 button", "^기록 보기$"); await page.waitForTimeout(600);
await clickText(".rb-main button", "^인물 위키"); await page.waitForTimeout(600);
await clickText(".rb-main button", "더보기"); await page.waitForTimeout(300);
ok("더보기 메뉴에 '봇 로어북으로 내보내기'", await clickText(".rb-menu *, [role=menu] *", "^봇 로어북으로 내보내기$"));
await page.waitForTimeout(500);
const rows = await page.locator(".rb-dialog .rb-lorex-row").allTextContents();
ok("정리된 정보가 있는 인물만 목록에 (시로코 O, 기록만 있는 인물·빈 문서는 X)", rows.length === 1 && rows[0].includes("시로코"), rows.join("|"));
if (process.env.SHOT) await page.screenshot({ path: process.env.SHOT });
const btnGo = page.locator(".rb-dialog .rb-dialog-actions button", { hasText: "내보내기" });
ok("고르기 전에는 내보내기가 꺼져 있음", await btnGo.isDisabled());
await page.locator(".rb-dialog .rb-lorex-row input[type=checkbox]").first().check();
ok("고르면 내보내기가 켜지고 인원 표시", (await btnGo.isEnabled()) && /1명/.test(await btnGo.textContent()));
await btnGo.click(); await page.waitForTimeout(600);
const w = await page.evaluate(() => window.__charWrites ?? []);
const lore = w[0]?.c?.globalLore ?? [];
ok("봇(c1)의 로어북에 항목 1개 저장", w.length === 1 && w[0].i === 0 && lore.length === 1, JSON.stringify(w.map((x) => x.i)));
ok("키는 이름, 표식, 항상 켜짐 아님, 정리된 글만(기록 사건 문구 없음)", lore[0]?.key.includes("시로코") && lore[0].extentions?.da_wiki === "시로코" && lore[0].alwaysActive === false && /차분하고 성실한/.test(lore[0].content) && !/순찰/.test(lore[0].content), lore[0]?.content);
ok("오류 없음", errs.length === 0, errs.join("|"));
await browser.close();
process.exit(out.every(Boolean) ? 0 : 1);
